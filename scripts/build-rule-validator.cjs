'use strict';
const fs = require('node:fs'), path = require('node:path');
const Ajv = require('ajv/dist/2020');
const standalone = require('ajv/dist/standalone').default;
const ajv = new Ajv({allErrors:true, strict:true, strictRequired:false, code:{source:true,lines:true}});
const code = standalone(ajv, ajv.compile(require('../public/rules/schema/rule-profile.schema.json')));
if (/\brequire\(/.test(code)) throw Error('Unexpected runtime dependency');
const output = '// Generated by npm run build:rules; do not edit.\n(function(root){var module={exports:{}};\n' +
code + '\nif(typeof exports==="object") exports.validate=module.exports; else root.GpaProfileSchema=module.exports;\n})(typeof self!=="undefined"?self:globalThis);\n';
const target=path.join(__dirname,'../public/js/rules/profile-schema-validator.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output) throw Error('Run npm run build:rules: generated validator is stale');
}else fs.writeFileSync(target,output);
